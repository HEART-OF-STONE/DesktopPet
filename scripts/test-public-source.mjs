import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, writeFileSync, unlinkSync } from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=process.cwd(), cache=path.join(root,'.cache');
mkdirSync(cache,{recursive:true});
const fixture=mkdtempSync(path.join(cache,'source-check-'));
execFileSync('git',['init','--quiet','--initial-branch=codex/security-check'],{cwd:fixture});
const scan=(...args)=>spawnSync(process.execPath,[path.join(root,'scripts/check-public-source.mjs'),...args],{cwd:fixture,encoding:'utf8'});
writeFileSync(path.join(fixture,'safe.txt'),'ordinary public source');
assert.equal(scan().status,0);
const synthetic='gh'+'p_'+'0'.repeat(36);
writeFileSync(path.join(fixture,'unsafe.txt'),synthetic);
let result=scan();assert.equal(result.status,1);assert.ok(!result.stderr.includes(synthetic));
execFileSync('git',['add','unsafe.txt'],{cwd:fixture});
writeFileSync(path.join(fixture,'unsafe.txt'),'working tree cleaned but index still contains synthetic credential');
assert.equal(scan('--staged').status,1);
execFileSync('git',['add','unsafe.txt'],{cwd:fixture});
execFileSync('git',['rm','--cached','--quiet','unsafe.txt'],{cwd:fixture});
unlinkSync(path.join(fixture,'unsafe.txt'));
writeFileSync(path.join(fixture,'secret.txt'),Buffer.from('untrusted comment: minisign encrypted secret key\n'+'0'.repeat(100)).toString('base64'));
assert.equal(scan().status,1);unlinkSync(path.join(fixture,'secret.txt'));
writeFileSync(path.join(fixture,'public.sig'),Buffer.from('untrusted comment: signature from tauri secret key\n'+'0'.repeat(100)).toString('base64'));
assert.equal(scan().status,0);
writeFileSync(path.join(fixture,'auth.json'),'{}');assert.equal(scan().status,1);
console.log('Source guard passed: public signature allowed, credential/private path/private key blocked, staged content checked, secret text never echoed.');
